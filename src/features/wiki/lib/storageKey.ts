import { READ_ONLY } from "./readOnly";

/**
 * 브라우저 저장소 키의 인스턴스 스코프 (설계 §2.2).
 *
 * `/wiki/`(팀 위키)와 `/docs/`(공개 문서)는 **같은 오리진**이라 localStorage를 통째로 공유한다.
 * 그래서 페이지·스페이스 **정체성을 담는** 키는 두 인스턴스가 같은 칸을 놓고 덮어쓴다. 실제로
 * 팀 위키에서 읽은 비공개 문서의 제목·id가 공개 화면의 "최근"·"별표" 목록에 뜨고, 그 id는 docs
 * DB에 존재하지 않아 깨진 링크가 된다 — 유출이면서 동시에 고장이다.
 *
 * 규칙: 읽기 전용 빌드만 `docs.` 접두사를 붙이고, 팀 위키는 **기존 키를 그대로 쓴다**. 기존 키를
 * 건드리면 이미 쓰고 있는 사용자의 별표·최근 기록이 한 번에 초기화된다.
 *
 * 컨텍스트(useReadOnly)가 아니라 빌드 상수를 쓰는 이유: 이 키를 읽는 모듈들은 React 밖의 순수
 * 함수(useSyncExternalStore의 getSnapshot 포함)라 훅을 부를 수 없고, 저장소 스코프는 렌더마다
 * 달라질 값도 아니다.
 *
 * 공유해도 되는 값은 감싸지 않는다 — 테마·사이드바 접힘/너비·코드블록 표시처럼 어떤 문서를 봤는지
 * 드러내지 않는 순수 취향 설정이다.
 */
export function scopedStorageKey(key: string): string {
  return READ_ONLY ? `docs.${key}` : key;
}
